type Option = [text: string, explanation: string];
function question(
  unitId: string,
  serial: number,
  pool: 'diagnostic' | 'practice',
  objective: number,
  concept: string,
  prompt: string,
  correct: Option,
  wrong1: Option,
  wrong2: Option,
  explanation: string,
  sourceId: string,
  locator: string,
  context: 'text' | 'case' = 'text',
  difficulty: 1 | 2 | 3 = 1,
  revision = 1,
): Question {
  const unit = foundationUnits.find((item) => item.id === unitId)!;
  const source = foundationSources.find((item) => item.id === sourceId)!;
  // Each content group describes a distinct assessed concept; these are not paraphrase variants.
  const original = [correct, wrong1, wrong2].map(([text, reason], index) => ({
    id: `c${index + 1}`,
    text,
    explanation: reason,
  }));
  const offset = serial % 3;
  return {
    id: `${unitId}-${pool === 'diagnostic' ? 'd' : 'p'}-${String(serial).padStart(2, '0')}`,
    revision,
    groupId: `${unitId}-${concept}`,
    domainId: unit.domainId,
    unitId,
    objectiveIds: [`${unitId}-o${objective}`],
    format: 'single_choice',
    context,
    difficulty,
    pool,
    prompt,
    choices: [...original.slice(offset), ...original.slice(0, offset)],
    correctChoiceId: 'c1',
    explanation,
    sourceRefs: [ref(sourceId, locator)],
    review: {
      status: 'source_checked',
      reviewerType: 'ai',
      checkedAt,
      revision,
      method: `${source.url} の「${locator}」をWebで実際に読み、設問・正答・各誤答理由・解説を該当記述と照合した。`,
      notes:
        'AIによる出典照合済み。人間の専門家によるレビューは未実施。公式試験問題の転載ではない。',
    },
  };
}

