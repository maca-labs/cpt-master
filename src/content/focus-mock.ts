type Answer = [text: string, explanation: string];

function caseQuestion(
  id: string,
  unitId: string,
  goal: number,
  source: [sourceId: string, locator: string],
  prompt: string,
  explanation: string,
  correct: Answer,
  distractorOne: Answer,
  distractorTwo: Answer,
): Question {
  const sourceRefs: SourceRef[] = [{ sourceId: source[0], locator: source[1] }];
  return {
    id: `focus-${id}`,
    groupId: `focus-${id}`,
    revision: 1,
    domainId: unitId.startsWith('ex-plan-') ? 'planning' : 'safety',
    unitId,
    objectiveIds: [`${unitId}-o${goal}`],
    format: 'single_choice',
    context: 'case',
    difficulty: 2,
    pool: 'focus',
    prompt,
    choices: [correct, distractorOne, distractorTwo].map(([text, explanation], index) => ({
      id: ['a', 'b', 'c'][index],
      text,
      explanation,
    })),
    correctChoiceId: 'a',
    explanation,
    sourceRefs,
    review: {
      status: 'source_checked',
      reviewerType: 'ai',
      method: 'AIが各出典の該当箇所と事例の条件・正答・誤答解説を照合。',
      checkedAt: '2026-11-08',
      revision: 1,
    },
  };
}

